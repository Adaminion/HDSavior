//! Checksums and digests used by the builder: SHA-256 for content and image
//! digests, CRC-32 and Adler-32 for the file formats in [`crate::content`],
//! FNV-1a 64 for cheap identity hashes.
//!
//! All of them are written from their public specifications (FIPS 180-4,
//! ISO 3309 / RFC 1952, RFC 1950) so that the crate needs no dependency
//! beyond `serde`; the tests check them against published vectors and, where
//! available, against `sha256sum` and Python's `zlib`.

/// Streaming SHA-256.
#[derive(Clone)]
pub struct Sha256 {
    state: [u32; 8],
    buf: [u8; 64],
    buf_len: usize,
    total: u64,
}

